#ifndef STRUCTURES_H
#define STRUCTURES_H

#include <QString>
#include <QList>

/**
 * @struct User
 * @brief Представляет собой модель данных одного пользователя в приложении.
 *
 * Эта структура используется для хранения и передачи всей информации,
 * связанной с конкретным пользователем, как в кэшах на клиенте,
 * так и для временного представления данных, полученных от сервера.
 */
struct User {
    qint64 id = 0;                  ///< Уникальный идентификатор пользователя в базе данных сервера.
    QString username;               ///< Уникальное имя пользователя (логин).
    QString displayName;            ///< Отображаемое имя пользователя.
    QString lastSeen;               ///< Дата и время последнего визита в формате ISO (например, "2025-10-15T10:00:00").
    QString avatarUrl;              ///< URL для загрузки аватара пользователя (задел на будущее).
    QString statusMessage;          ///< Личное статусное сообщение пользователя (задел на будущее).

    // --- Поля состояния, управляемые на клиенте в реальном времени ---
    bool isTyping = false;          ///< Флаг, указывающий, печатает ли пользователь сообщение в данный момент.
    bool isOnline = false;          ///< Флаг, указывающий, находится ли пользователь в сети.
};

/**
 * @struct ChatMessage
 * @brief Представляет собой модель данных одного сообщения в чате.
 *
 * Эта структура является основной единицей обмена и хранения в переписках.
 */
struct ChatMessage {

    /**
     * @enum MessageType
     * @brief Определяет тип содержимого сообщения. (Задел на будущее).
     */
    enum MessageType {
        Text,    ///< Обычное текстовое сообщение.
        Image,   ///< Сообщение с изображением.
        File,    ///< Сообщение с файлом.
        Sticker, ///< Сообщение-стикер.
        System   ///< Системное уведомление в чате (например, "Пользователь присоединился").
    };

    /**
     * @enum MessageStatus
     * @brief Определяет жизненный цикл и статус доставки исходящего сообщения.
     */
    enum MessageStatus {
        Sending,   ///< Сообщение отправляется (еще не получило подтверждения от сервера).
        Sent,      ///< Сообщение успешно доставлено на сервер.
        Delivered, ///< Сообщение доставлено получателю.
        Read,      ///< Получатель прочитал сообщение.
        Error      ///< Произошла ошибка при отправке сообщения.
    };

    // --- Основные данные сообщения ---
    qint64 id = 0;                 ///< Уникальный ID сообщения из базы данных сервера. 0 для еще не отправленных.
    QString tempId;                 ///< Временный уникальный ID, генерируемый клиентом. Используется для сопоставления "отправленного" сообщения с "подтвержденным" от сервера.
    QString fromUser;               ///< `username` отправителя.
    QString toUser;                 ///< `username` получателя.
    QString payload;                ///< Основное содержимое сообщения (текст, URL файла и т.д.).
    QString timestamp;              ///< Дата и время отправки в формате ISO.

    // --- Метаданные и флаги ---
    bool isEdited = false;          ///< Флаг, указывающий, было ли сообщение отредактировано.
    qint64 replyToId = 0;           ///< ID сообщения, на которое это сообщение является ответом. 0, если это не ответ.
    User forwardedFrom;             ///< Данные пользователя, от которого было переслано сообщение (задел на будущее).
    MessageType messageType;        ///< Тип сообщения из `enum MessageType` (задел на будущее).
    MessageStatus status;           ///< Текущий статус доставки сообщения.
    QString mediaUrl;               ///< URL для загрузки медиа-контента (задел на будущее).
    bool isOutgoing;                ///< Флаг, определяемый на стороне клиента. `true`, если сообщение отправлено текущим пользователем.
};
inline bool operator==(const ChatMessage& lhs, const ChatMessage& rhs) {
    return lhs.id == rhs.id;
}

/**
 * @struct ChatCache
 * @brief Структура для кэширования истории одного чата в оперативной памяти клиента.
 *
 * Используется в `MainWindow` для мгновенного отображения переписок
 * при переключении между контактами без повторных запросов к серверу.
 */
struct ChatCache {
    QList<ChatMessage> messages;     ///< Список всех загруженных сообщений для данного чата.
    qint64 oldestMessageId = -1;     ///< ID самого старого из загруженных сообщений. Используется для пагинации (запроса более старой истории). -1 означает, что история еще не загружалась.
    bool allMessagesLoaded = false;  ///< Флаг, указывающий, что вся история для этого чата была загружена и больше нет смысла отправлять запросы `get_history`.
};
struct CallInfo {
    QString callId;
    QString from;
    QString to;
    QObject* fromSocket;     // указатель на сокет инициатора
    QObject* toSocket;       // указатель на сокет принимающего
    quint16 callerPort;
    QString callerIp;
};
#endif // STRUCTURES_H

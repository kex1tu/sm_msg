/**
 * @file main.cpp
 * @brief Точка входа в приложение чат-клиента.
 *
 * @details Этот файл содержит функцию `main`, которая является первой функцией,
 * вызываемой при запуске программы. Она отвечает за:
 * 1. Создание экземпляра `QApplication` - ядра любого Qt GUI-приложения.
 * 2. Загрузку и применение глобальной таблицы стилей (QSS) ко всему приложению.
 * 3. Создание и отображение главного окна (`MainWindow`).
 * 4. Запуск главного цикла обработки событий Qt.
 * @author kex1tu
 */

#include "mainwindow.h" // Включаем заголовочный файл нашего главного окна.
#include <QFile>         // Для работы с файлами (в данном случае, с файлом стилей из ресурсов).
#include <QDebug>        // Для вывода отладочной информации (qDebug, qWarning).
#include <QApplication>  // Основной класс для управления GUI-приложением.

/**
 * @brief Главная функция, точка входа в программу.
 * @param argc Количество аргументов командной строки.
 * @param argv Массив строк, содержащий аргументы командной строки.
 * @return int Код завершения программы.
 */
int main(int argc, char *argv[])
{
    // 1. Создание объекта QApplication. Этот объект должен быть создан
    //    самым первым, так как он управляет всеми ресурсами приложения,
    //    обработкой событий и т.д.
    QApplication a(argc, argv);

    // --- 2. Загрузка и применение глобальной таблицы стилей (QSS) ---
    // Указываем путь к файлу стилей в системе ресурсов Qt (префикс ":/").
    QFile styleFile(":/styles.css");

    // Пытаемся открыть файл только для чтения.
    if (!styleFile.open(QFile::ReadOnly)) {
        // Если файл не удалось открыть (например, ошибка в пути или в .qrc файле),
        // выводим предупреждение в консоль. Приложение продолжит работу, но без стилей.
        qWarning() << "Warning: Could not open style file from resources.";
    } else {
        // Если файл успешно открыт:
        // Считываем все его содержимое в строку. QLatin1String - это оптимизация,
        // которая говорит, что наш CSS-файл не содержит не-латинских символов.
        QString styleSheet = QLatin1String(styleFile.readAll());

        // Применяем считанные стили ко всему приложению.
        a.setStyleSheet(styleSheet);

        qDebug() << "Style sheet loaded successfully."; // Выводим сообщение об успехе.

        styleFile.close(); // Закрываем файл.
    }

    // 3. Создание экземпляра нашего главного окна.
    MainWindow w;

    // 4. Отображение главного окна на экране.
    w.show();

    // 5. Запуск главного цикла обработки событий Qt.
    //    Эта функция блокирует выполнение и передает управление Qt.
    //    Она будет выполняться до тех пор, пока приложение не будет закрыто
    //    (например, через вызов w.close() или QApplication::quit()).
    //    Возвращает код завершения, который передается операционной системе.
    return a.exec();
}
